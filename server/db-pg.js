export function uuid() {
  return randomUUID();
}

export function now() {
  return new Date().toISOString();
}

export function isPg(db) {
  return db._pg !== undefined;
}

export async function closeDatabase(db) {
  if (db._pg) {
    await db._pg.end();
  } else {
    db.close();
  }
}

// ---------------------------------------------------------------------------
// openDatabasePg: create a PostgreSQL-backed db object for createApp
// ---------------------------------------------------------------------------

// The returned object must satisfy the parts of the SQLite DatabaseSync API
// that the application actually uses. The application calls:
//   db.prepare(sql).get(...params)
//   db.prepare(sql).all(...params)
//   db.prepare(sql).run(...params)
//   db.exec(sql)            (used for PRAGMA and VACUUM INTO and multi-statement scripts)
//   db.transaction(fn)      (async for PostgreSQL)
//   db.close()
//   db.prepare("PRAGMA user_version").get().user_version   (SQLite only; PG uses _schema_version)
//
// For PostgreSQL we provide an async-compatible wrapper. The application's
// createApp uses db.prepare(...).get(...) synchronously for SQLite; for
// PostgreSQL those calls become promises. This is the main compatibility gap:
// all call sites in app.js must be adapted to await PostgreSQL queries.
// We address this by exporting an async helper that the app uses when PG is
// active.

export function openDatabasePg() {
  const pool = getPool();

  const db = {
    _pg: pool,
    prepare(sql) {
      return new PgPrepared(pool, sql);
    },
    async exec(sql) {
      // For multi-statement scripts we execute them as a single query. pg
      // allows multiple statements in one query string when connected with
      // a simple query protocol. For safety we only use this for DDL that we
      // know is safe.
      return pool.query(sql);
    },
    async transaction(fn) {
      return transaction(pool, fn);
    },
    async close() {
      await pool.end();
    },
    async ready() {
      const ver = await pool.query(
        "SELECT version FROM _schema_version ORDER BY version DESC LIMIT 1",
      );
      return ver.rows[0]?.version || 0;
    },
  };

  return db;
}

// ---------------------------------------------------------------------------
// SQL compatibility helpers
// ---------------------------------------------------------------------------

// The application builds search predicates like:
//   instr(lower(title||' '||owner||' '||category||' '||notes), ?) > 0
//
// For PostgreSQL we use:
//   POSITION(LOWER(title || ' ' || owner || ' ' || category || ' ' || notes) IN LOWER($n)) > 0
//
// This function returns the SQL snippet given the column expression and the
// parameter index.
export function searchPattern(field, paramIndex) {
  return `POSITION(LOWER(${field}) IN LOWER($${paramIndex})) > 0`;
}

// INSERT OR IGNORE replacement for PostgreSQL.
// SQLite: INSERT OR IGNORE INTO t (...) VALUES (...)
// PostgreSQL: INSERT INTO t (...) VALUES (...) ON CONFLICT DO NOTHING
//
// This is used for read_notifications marking. We inline the pattern where
// needed rather than exporting a generic wrapper.
export function insertOnConflictDoNothing() {
  return "ON CONFLICT DO NOTHING";
}

// INSERT OR REPLACE replacement for PostgreSQL.
// SQLite: INSERT OR REPLACE INTO t (...) VALUES (...)
// PostgreSQL: INSERT INTO t (...) VALUES (...) ON CONFLICT (pk) DO UPDATE SET ...
// We inline the pattern where needed.
