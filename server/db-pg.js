export const schemaVersion = () => 2;

async function runMigration(pool, version) {
  if (version === 1) {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS users (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT UNIQUE NOT NULL,
        password TEXT NOT NULL,
        role TEXT NOT NULL,
        mines JSONB NOT NULL DEFAULT '[]'::jsonb
      );

      CREATE TABLE IF NOT EXISTS sessions (
        token TEXT PRIMARY KEY,
        user_id TEXT NOT NULL REFERENCES users(id),
        expires timestamptz NOT NULL
      );

      CREATE TABLE IF NOT EXISTS mines (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        subsidiary TEXT NOT NULL,
        region TEXT NOT NULL,
        latitude DOUBLE PRECISION NOT NULL,
        longitude DOUBLE PRECISION NOT NULL,
        capacity DOUBLE PRECISION NOT NULL
      );

      CREATE TABLE IF NOT EXISTS records (
        id TEXT PRIMARY KEY,
        kind TEXT NOT NULL,
        mine_id TEXT NOT NULL REFERENCES mines(id),
        title TEXT NOT NULL,
        category TEXT NOT NULL,
        status TEXT NOT NULL,
        priority TEXT NOT NULL,
        due_date DATE,
        owner TEXT NOT NULL,
        notes TEXT NOT NULL,
        data JSONB NOT NULL,
        created_by TEXT REFERENCES users(id),
        created_at timestamptz NOT NULL,
        updated_at timestamptz NOT NULL,
        version INTEGER NOT NULL DEFAULT 1
      );

      CREATE INDEX IF NOT EXISTS idx_records_kind_mine
        ON records(kind, mine_id);
      CREATE INDEX IF NOT EXISTS idx_records_mine_created
        ON records(mine_id, created_at DESC);
      CREATE INDEX IF NOT EXISTS idx_records_mine_kind_created
        ON records(mine_id, kind, created_at DESC);

      CREATE TABLE IF NOT EXISTS documents (
        id TEXT PRIMARY KEY,
        mine_id TEXT NOT NULL REFERENCES mines(id),
        name TEXT NOT NULL,
        mime TEXT NOT NULL,
        size INTEGER NOT NULL,
        storage_name TEXT NOT NULL,
        text TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL,
        created_by TEXT NOT NULL REFERENCES users(id),
        created_at timestamptz NOT NULL
      );

      CREATE INDEX IF NOT EXISTS idx_documents_mine_created
        ON documents(mine_id, created_at DESC);

      CREATE TABLE IF NOT EXISTS embeddings (
        document_id TEXT PRIMARY KEY REFERENCES documents(id),
        model TEXT NOT NULL,
        vector JSONB NOT NULL
      );

      CREATE TABLE IF NOT EXISTS audit (
        id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        actor TEXT NOT NULL,
        actor_name TEXT NOT NULL,
        action TEXT NOT NULL,
        entity TEXT NOT NULL,
        mine_id TEXT,
        payload JSONB NOT NULL,
        created_at timestamptz NOT NULL,
        previous_hash TEXT NOT NULL,
        hash TEXT NOT NULL
      );

      CREATE INDEX IF NOT EXISTS idx_audit_mine_id
        ON audit(mine_id, id DESC);

      CREATE TABLE IF NOT EXISTS read_notifications (
        user_id TEXT NOT NULL REFERENCES users(id),
        notification_id TEXT NOT NULL,
        PRIMARY KEY(user_id, notification_id)
      );

      CREATE TABLE IF NOT EXISTS idempotency (
        user_id TEXT NOT NULL,
        key TEXT NOT NULL,
        record_id TEXT NOT NULL,
        PRIMARY KEY(user_id, key)
      );

      CREATE TABLE IF NOT EXISTS _schema_version (
        version INTEGER PRIMARY KEY,
        applied_at timestamptz NOT NULL DEFAULT now()
      );
    `);
  }

  if (version === 2) {
    await pool.query(`
      CREATE INDEX IF NOT EXISTS idx_sessions_expires
        ON sessions(expires);

      CREATE TABLE IF NOT EXISTS audit_anchor (
        id INTEGER PRIMARY KEY CHECK(id = 1),
        entries INTEGER NOT NULL,
        head TEXT NOT NULL
      );
    `);
  }
}

async function initialiseAuditAnchor(pool) {
  const anchorRow = await pool.query(
    "SELECT id FROM audit_anchor WHERE id = 1",
  );
  if (anchorRow.rows[0]) return;

  const countRes = await pool.query("SELECT COUNT(*) AS n FROM audit");
  const count = parseInt(countRes.rows[0].n, 10);

  if (count === 0) {
    await pool.query(
      "INSERT INTO audit_anchor(id, entries, head) VALUES(1, 0, 'GENESIS')",
    );
    return;
  }

  const rows = await pool.query(
    "SELECT id, hash, previous_hash FROM audit ORDER BY id",
  );
  let prev = "GENESIS";
  for (const row of rows.rows) {
    if (row.previous_hash !== prev) return; // broken chain: do not anchor
    prev = row.hash;
  }

  await pool.query(
    "INSERT INTO audit_anchor(id, entries, head) VALUES(1, $1, $2)",
    [count, prev],
  );
}

export async function migrate(pool) {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS _schema_version (
      version INTEGER PRIMARY KEY,
      applied_at timestamptz NOT NULL DEFAULT now()
    );
  `);

  const existing = await pool.query(
    "SELECT version FROM _schema_version ORDER BY version DESC LIMIT 1",
  );
  const applied = existing.rows[0]?.version || 0;

  if (applied > schemaVersion()) {
    throw new Error(
      `Database schema version ${applied} is newer than this build (${schemaVersion()}). Upgrade the application or restore an older backup.`,
    );
  }

  for (let v = applied + 1; v <= schemaVersion(); v++) {
    await pool.query("BEGIN");
    try {
      await runMigration(pool, v);
      await pool.query(
        "INSERT INTO _schema_version(version, applied_at) VALUES($1, now())",
        [v],
      );
      await pool.query("COMMIT");
    } catch (err) {
      await pool.query("ROLLBACK");
      throw new Error(
        `Database migration ${v} failed: ${err.message}`,
      );
    }
  }

  // After all migrations are applied, initialise the audit anchor if needed.
  // This runs after the schema is current so the anchor reflects the final
  // state of the audit table.
  await initialiseAuditAnchor(pool);
}

// ---------------------------------------------------------------------------
// Transaction handling
// ---------------------------------------------------------------------------

export async function transaction(pool, fn) {
  const client = await pool.connect();
  let reusable = true;
  try {
    await client.query("BEGIN");
    const result = await fn(client);
    await client.query("COMMIT");
    return result;
  } catch (err) {
    try {
      await client.query("ROLLBACK");
    } catch (rollbackErr) {
      reusable = false;
      console.error("Transaction rollback failed:", rollbackErr.message);
    }
    throw err;
  } finally {
    client.release(!reusable);
  }
}

// ---------------------------------------------------------------------------
// Audit functions (PostgreSQL implementation)
// ---------------------------------------------------------------------------

export async function audit(pool, user, action, entity, mineId, payload = {}) {
  const client = await pool.connect();
  let reusable = true;
  try {
    await client.query("BEGIN");
    const prev =
      (
        await client.query(
          "SELECT hash FROM audit ORDER BY id DESC LIMIT 1",
        )
      ).rows[0]?.hash || "GENESIS";

    const entry = {
      actor: user.id,
      actor_name: user.name,
      action,
      entity,
      mine_id: mineId || null,
      payload,
      created_at: new Date().toISOString(),
      previous_hash: prev,
    };

    const hash = createHash("sha256")
      .update(JSON.stringify(entry))
      .digest("hex");

    await client.query(
      `INSERT INTO audit(actor, actor_name, action, entity, mine_id, payload, created_at, previous_hash, hash)
       VALUES($1, $2, $3, $4, $5, $6, $7, $8, $9)`,
      [
        entry.actor,
        entry.actor_name,
        entry.action,
        entry.entity,
        entry.mine_id,
        entry.payload,
        entry.created_at,
        entry.previous_hash,
        hash,
      ],
    );

    // Advance the anchored head by one rather than counting the table, so an
    // audit write stays O(1) as the log grows.
    const anchorRes = await client.query(
      "SELECT entries FROM audit_anchor WHERE id = 1",
    );
    const entries = (anchorRes.rows[0]?.entries ?? 0) + 1;

    await client.query(
      `INSERT INTO audit_anchor(id, entries, head) VALUES(1, $1, $2)
       ON CONFLICT (id) DO UPDATE SET entries = $1, head = $2`,
      [entries, hash],
    );

    await client.query("COMMIT");
    return hash;
  } catch (err) {
    try {
      await client.query("ROLLBACK");
    } catch (rollbackErr) {
      reusable = false;
      console.error("Audit rollback failed:", rollbackErr.message);
    }
    throw err;
  } finally {
    client.release(!reusable);
  }
}

export async function verifyAudit(pool) {
  const rows = await pool.query("SELECT * FROM audit ORDER BY id");
  let prev = "GENESIS";
  let count = 0;

  for (const row of rows.rows) {
    const { id, hash, ...entry } = row;
    // PostgreSQL returns JSONB as a parsed object; normalise to the shape used
    // when the hash was computed.
    const payloadForHash =
      typeof entry.payload === "object" ? entry.payload : JSON.parse(entry.payload);

    const canonical = {
      actor: entry.actor,
      actor_name: entry.actor_name,
      action: entry.action,
      entity: entry.entity,
      mine_id: entry.mine_id,
      payload: payloadForHash,
      created_at: entry.created_at,
      previous_hash: entry.previous_hash,
    };

    if (
      entry.previous_hash !== prev ||
      createHash("sha256").update(JSON.stringify(canonical)).digest("hex") !==
        hash
    ) {
      return { valid: false, count, brokenAt: id, anchor: null };
    }
    prev = hash;
    count++;
  }

  const anchorRes = await pool.query(
    "SELECT * FROM audit_anchor WHERE id = 1",
  );
  const anchor = anchorRes.rows[0] || null;

  if (anchor && (anchor.entries !== count || anchor.head !== prev)) {
    return {
      valid: false,
      count,
      brokenAt: null,
      anchor: { entries: anchor.entries, head: anchor.head },
      reason:
        count < anchor.entries
          ? "The audit log is shorter than its anchored length; entries appear to have been removed."
          : "The audit log does not match its anchored head hash; entries appear to have been altered.",
    };
  }

  return {
    valid: true,
    count,
    head: prev,
    anchor: anchor ? anchor.entries : null,
  };
}

// ---------------------------------------------------------------------------
// Compatible query wrappers
// ---------------------------------------------------------------------------

// The application calls db.prepare(sql).get(...params), .all(...params) and
// .run(...params). We provide wrappers that look the same and return compatible
// results.

class PgPrepared {
  constructor(pool, sql) {
    this._pool = pool;
    this._sql = sql;
  }

  get(...params) {
    return this._pool.query(this._sql, params).then((res) => res.rows[0] || null);
  }

  all(...params) {
    return this._pool.query(this._sql, params).then((res) => res.rows);
  }

  async run(...params) {
    const res = await this._pool.query(this._sql, params);
    return {
      rowsAffected: res.rowCount,
      rows: res.rows,
    };
  }
}

// A return-value wrapper that mimics SQLite's result object for run().
// The application checks .changes occasionally (not used in current code) and
// uses .lastInsertRowid for inserts that need the generated id. For PostgreSQL
// we return a compatible object with lastInsertRowid set to the inserted id
// when the statement includes RETURNING id.
class PgRunResult {
  constructor(rowCount, lastId) {
    this.rowsAffected = rowCount;
    this.changes = rowCount;
    this.lastInsertRowid = lastId;
  }
}

// ---------------------------------------------------------------------------
// Record normalisation
// ---------------------------------------------------------------------------

// The SQLite backend stores data as TEXT and JSON.parses it. PostgreSQL stores
// it as JSONB and returns it as a parsed object. Normalise to the same shape.
export function record(row) {
  if (!row) return null;
  const {
    mine_id,
    due_date,
    created_at,
    updated_at,
    created_by,
    data,
    ...rest
  } = row;
  return {
    ...rest,
    mineId: mine_id,
    dueDate: due_date,
    createdAt: created_at,
    updatedAt: updated_at,
    createdBy: created_by,
    data:
      typeof data === "string" ? JSON.parse(data) : data,
  };
}

