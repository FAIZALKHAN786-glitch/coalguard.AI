// PostgreSQL database adapter for CoalGuard AI.
//
// Provides a PostgreSQL-backed database object that is API-compatible with the
// SQLite backend used in db.js, so createApp and the route handlers can work
// with either backend without knowing which one is in use.
//
// Architecture:
//  - One pg.Pool per process, configured from DATABASE_URL and optional PG_*
//    environment variables (PG_HOST, PG_PORT, PG_USER, PG_PASSWORD,
//    PG_DATABASE, PG_SSL, PG_POOL_MAX, PG_CA_CERT, and others).
//  - Transactions use a single checked-out client so BEGIN/COMMIT/ROLLBACK stay
//    on one connection.
//  - Parameterised queries everywhere ($1, $2, …). No string interpolation of
//    user input into SQL.
//  - UUID primary keys are generated by the application (randomUUID) and stored
//    as TEXT, matching the existing schema contract.
//  - Audit hash chain and anchor are implemented identically to SQLite, using
//    text columns and application-computed SHA-256 hashes.
//  - SQLite-specific SQL is removed: no AUTOINCREMENT, no INSERT OR REPLACE,
//    no INSERT OR IGNORE, no PRAGMA, no rowid-dependent queries.
//
// Known differences from the SQLite backend that callers must be aware of:
//  - PostgreSQL returns JSONB columns as parsed JavaScript objects, not strings.
//    The record() helper normalises this so callers see the same shape.
//  - Timestamps are stored as timestamptz; the application passes ISO strings,
//    which PostgreSQL accepts for timestamptz columns.
//  - The audit anchor initialise-on-migrate logic runs inside migratePg().

import { Pool } from "pg";
import { randomUUID, createHash } from "node:crypto";

// ---------------------------------------------------------------------------
// Pool configuration
// ---------------------------------------------------------------------------

function buildPool() {
  const url = new URL(process.env.DATABASE_URL);

  const config = {
    connectionString: process.env.DATABASE_URL,
    max: Number(process.env.PG_POOL_MAX || 10),
    idleTimeoutMillis: Number(process.env.PG_POOL_IDLE_TIMEOUT_MS || 30000),
    connectionTimeoutMillis: Number(
      process.env.PG_POOL_CONNECTION_TIMEOUT_MS || 2000,
    ),
    statement_timeout: Number(process.env.PG_STATEMENT_TIMEOUT_MS || 10000),
    query_timeout: Number(process.env.PG_QUERY_TIMEOUT_MS || 10000),
    lock_timeout: Number(process.env.PG_LOCK_TIMEOUT_MS || 5000),
  };

  // Override connection string fields with explicit PG_* variables when they
  // are set, so operators can configure the connection without editing
  // DATABASE_URL.
  if (process.env.PG_HOST) {
    config.host = process.env.PG_HOST;
    config.port = Number(process.env.PG_PORT || 5432);
    if (process.env.PG_USER) config.user = process.env.PG_USER;
    if (process.env.PG_PASSWORD) config.password = process.env.PG_PASSWORD;
    if (process.env.PG_DATABASE) config.database = process.env.PG_DATABASE;
  }

  // Clamp pool size to sane bounds.
  if (!Number.isFinite(config.max) || config.max < 1) config.max = 10;
  if (!Number.isFinite(config.max) || config.max > 100) config.max = 100;

  // TLS configuration for production.
  if (process.env.PG_SSL === "true") {
    config.ssl = {
      rejectUnauthorized: true,
      ...(process.env.PG_CA_CERT ? { ca: process.env.PG_CA_CERT } : {}),
      ...(process.env.PG_CLIENT_CERT
        ? { cert: process.env.PG_CLIENT_CERT }
        : {}),
      ...(process.env.PG_CLIENT_KEY ? { key: process.env.PG_CLIENT_KEY } : {}),
    };
  } else if (process.env.PG_SSL === "require") {
    // Some hosted providers only require TLS without client certificates.
    config.ssl = { rejectUnauthorized: true };
  }

  return new Pool(config);
}

let pool = null;

export function getPool() {
  if (!pool) pool = buildPool();
  return pool;
}

export function resetPoolForTesting() {
  if (pool) {
    pool.end().catch(() => {});
    pool = null;
  }
}

